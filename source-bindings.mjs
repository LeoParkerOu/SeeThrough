import { readFile, realpath, lstat, writeFile, rename } from 'node:fs/promises';
import { resolve, sep } from 'node:path';
import { createHash } from 'node:crypto';
import { graphRootOf, sourceLocation } from './graph-library.mjs';

const sha = text => createHash('sha256').update(text).digest('hex');
const valid = state => state === 'verified' || state === 'relocated';
const refIdentity = ref => ({ path: ref.path, symbol: ref.symbol ?? null, startLine: ref.startLine, endLine: ref.endLine });
const identityHash = ref => sha(JSON.stringify(refIdentity(ref)));
const meaningHash = node => sha(JSON.stringify(['label', 'description', 'annotation', 'role', 'parentId', 'input', 'output'].map(key => [key, node.data?.[key] ?? null])));
const excluded = path => /(^|\/)(node_modules|vendor|dist|build|coverage|\.git)(\/|$)|\.min\.[cm]?js$/.test(path);

export async function safeSourcePath(scope, path, { allowMissing = false } = {}) {
  const location = sourceLocation(scope, path), allowed = await realpath(location.root);
  let candidate = allowed;
  const parts = location.path.split('/');
  for (const [index, part] of parts.entries()) {
    candidate = resolve(candidate, part);
    try {
      const stat = await lstat(candidate);
      if (stat.isSymbolicLink()) throw new Error('源码引用不能使用符号链接（防止越出工作区）');
      if (index < parts.length - 1 && !stat.isDirectory()) throw new Error('源码引用父路径不是目录');
      if (index === parts.length - 1 && !stat.isFile()) throw new Error('源码引用不是普通文件');
    } catch (error) {
      if (allowMissing && index === parts.length - 1 && error.code === 'ENOENT') return candidate;
      throw error;
    }
  }
  const full = await realpath(candidate);
  if (!full.startsWith(allowed + sep)) throw new Error('源码引用越出工作区');
  return full;
}

// Logical scale only: physical lines containing content outside comments.
// Braces and string/template contents count. This is not complexity.
export function effectiveLineNumbers(text) {
  const result = new Set();
  let block = false, quote = null, escaped = false;
  for (const [index, line] of text.split('\n').entries()) {
    let content = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i], next = line[i + 1];
      if (block) { if (ch === '*' && next === '/') { block = false; i++; } continue; }
      if (quote) {
        if (!/\s/.test(ch)) content = true;
        if (escaped) { escaped = false; continue; }
        if (ch === '\\') { escaped = true; continue; }
        if (ch === quote) quote = null;
        continue;
      }
      if (ch === '/' && next === '/') break;
      if (ch === '/' && next === '*') { block = true; i++; continue; }
      if (ch === '"' || ch === "'" || ch === '`') quote = ch;
      if (!/\s/.test(ch)) content = true;
    }
    if (content) result.add(index + 1);
    if (quote !== '`' && !escaped) quote = null;
    escaped = false;
  }
  return result;
}

async function bindingFile(root) {
  try {
    const path = await safeSourcePath(graphRootOf(root), 'factory.bindings.json');
    const raw = await readFile(path, 'utf8');
    const value = JSON.parse(raw);
    if (value.schemaVersion !== 1 || !value.nodes || typeof value.nodes !== 'object') throw new Error('绑定文件格式错误');
    return { raw, value };
  } catch (error) {
    if (error.code === 'ENOENT') return { raw: '', value: { schemaVersion: 1, nodes: {}, reviews: [] } };
    return { raw: `invalid:${error.message}`, value: { schemaVersion: 1, nodes: {}, reviews: [] }, error: error.message };
  }
}
function checkRange(ref, lines) {
  if (!Number.isInteger(ref.startLine) || !Number.isInteger(ref.endLine) || ref.startLine < 1 || ref.endLine < ref.startLine || ref.endLine > lines.length) throw new Error('源码引用行号失效');
}
function occurrences(lines, snippet) {
  const matches = [];
  for (let i = 0; i <= lines.length - snippet.length; i++) {
    if (snippet.every((line, j) => lines[i + j] === line)) matches.push(i + 1);
    if (matches.length > 1) break;
  }
  return matches;
}

export async function inspectBindings(root, graph, raw) {
  const binding = await bindingFile(root);
  const files = new Map(), fingerprints = new Map(), ownKeys = new Map(), ownStates = new Map();
  async function getFile(path) {
    if (!files.has(path)) files.set(path, (async () => {
      try {
        const full = await safeSourcePath(root, path);
        const text = await readFile(full, 'utf8');
        const value = { full, text, lines: text.split('\n'), hash: sha(text), effective: effectiveLineNumbers(text), excluded: excluded(path) || /@generated|<auto-generated>|DO NOT EDIT.*generated/i.test(text.slice(0, 1000)) };
        fingerprints.set(path, value.hash);
        return value;
      } catch (error) { fingerprints.set(path, `error:${error.code ?? ''}:${error.message}`); throw error; }
    })());
    return files.get(path);
  }
  for (const node of graph.nodes) {
    node.data ??= {};
    const refs = [], keys = new Set(), stored = binding.value.nodes[node.id];
    for (const ref of node.data.sourceRefs ?? []) {
      const result = { declaredRef: refIdentity(ref), state: 'unverified' };
      refs.push(result);
      let file;
      try { file = await getFile(ref.path); }
      catch (error) { Object.assign(result, { state: 'stale', reason: error.code === 'ENOENT' ? 'source-missing' : error.message }); continue; }
      result.fileHash = file.hash;
      if (binding.error) { Object.assign(result, { state: 'stale', reason: `binding-invalid: ${binding.error}` }); continue; }
      if (!stored) { result.reason = 'no-reviewed-binding'; continue; }
      if (stored.meaningHash !== meaningHash(node)) { Object.assign(result, { state: 'stale', reason: 'component-description-changed' }); continue; }
      const anchor = stored.refs?.find(item => item.refHash === identityHash(ref));
      if (!anchor) { Object.assign(result, { state: 'stale', reason: 'source-reference-changed' }); continue; }
      if (!anchor.ref || typeof anchor.snippet !== 'string' || sha(anchor.snippet) !== anchor.anchorHash) { Object.assign(result, { state: 'stale', reason: 'binding-anchor-invalid' }); continue; }
      const matches = occurrences(file.lines, anchor.snippet.split('\n'));
      if (matches.length !== 1) { Object.assign(result, { state: 'stale', reason: matches.length ? 'anchor-ambiguous' : 'source-content-changed' }); continue; }
      const startLine = matches[0], endLine = startLine + anchor.snippet.split('\n').length - 1;
      Object.assign(result, { state: startLine === anchor.ref.startLine ? 'verified' : 'relocated', currentRef: { ...ref, startLine, endLine }, canonicalPath: file.full, anchorHash: anchor.anchorHash,
        numberedText: file.lines.slice(startLine - 1, endLine).map((line, i) => `${startLine + i}: ${line}`).join('\n'), excludedFromSize: file.excluded });
      if (!file.excluded) for (let line = startLine; line <= endLine; line++) if (file.effective.has(line)) keys.add(`${file.full}:${line}`);
    }
    const state = !refs.length ? 'unverified' : refs.some(r => r.state === 'stale') ? 'stale' : refs.some(r => r.state === 'unverified') ? 'unverified' : refs.some(r => r.state === 'relocated') ? 'relocated' : 'verified';
    ownKeys.set(node.id, keys); ownStates.set(node.id, state);
    node.data.currentSourceRefs = refs.filter(r => valid(r.state)).map(r => r.currentRef);
    node.data.sourceStatus = { state, ownState: state, explanationReady: valid(state), refs, issues: refs.filter(r => !valid(r.state)).map(r => ({ path: r.declaredRef.path, reason: r.reason })), reviewedAt: stored?.reviewedAt ?? null };
  }
  const byId = new Map(graph.nodes.map(n => [n.id, n])), done = new Set();
  function aggregate(node, stack = new Set()) {
    if (done.has(node.id)) return node._sizeKeys;
    if (stack.has(node.id)) throw new Error('组件归属循环，无法核对代码规模');
    stack = new Set([...stack, node.id]);
    const keys = new Set(ownKeys.get(node.id)), states = [ownStates.get(node.id)];
    for (const child of graph.nodes.filter(n => n.data.parentId === node.id)) {
      for (const key of aggregate(child, stack)) keys.add(key);
      states.push(child.data.sourceStatus.state);
      if (!valid(child.data.sourceStatus.state)) node.data.sourceStatus.issues.push({ nodeId: child.id, reason: 'descendant-source-untrusted' });
    }
    if (node.data.parentId && !byId.has(node.data.parentId)) { states.push('stale'); node.data.sourceStatus.issues.push({ reason: 'parent-component-missing' }); }
    const state = states.includes('stale') ? 'stale' : states.includes('unverified') ? 'unverified' : states.includes('relocated') ? 'relocated' : 'verified';
    Object.assign(node.data.sourceStatus, { state, explanationReady: valid(state) });
    node.data.codeSize = { lines: valid(state) ? keys.size : null, ownLines: valid(ownStates.get(node.id)) ? ownKeys.get(node.id).size : null,
      basis: 'mapped-source-lines', scope: 'node-and-descendants', method: 'nonblank-noncomment-lines',
      note: '按文件真实路径和行号去重；当前注释识别用于本示例JS代码。排除空白、纯注释、依赖/构建目录及有生成标记的文件。统计已关联代码，不等于复杂度、重要性或全部项目代码。',
      ...(!valid(state) ? { reason: 'source-mapping-untrusted' } : {}) };
    node._sizeKeys = keys; done.add(node.id); return keys;
  }
  for (const node of graph.nodes) aggregate(node);
  for (const node of graph.nodes) delete node._sizeKeys;
  const graphHash = sha(JSON.stringify([raw, sha(binding.raw), [...fingerprints].sort(([a], [b]) => a.localeCompare(b))]));
  graph.meta ??= {};
  graph.meta.sourceIntegrity = { bindingVersion: 1, counts: Object.fromEntries(['verified', 'relocated', 'stale', 'unverified'].map(state => [state, graph.nodes.filter(n => n.data.sourceStatus.state === state).length])), note: '绑定仅在显式核验命令或工具中更新，轮询读取不会重新背书。' };
  return { graph, graphHash };
}

export async function reviewBindings(root, { nodeIds, expectedGraphHash, reason, reviewer = 'agent' }) {
  if (!Array.isArray(nodeIds) || !nodeIds.length || new Set(nodeIds).size !== nodeIds.length) throw new Error('请明确列出本次已核验的组件 ID');
  if (typeof reason !== 'string' || reason.trim().length < 8) throw new Error('必须说明已核对的代码行为、组件描述与引用范围（至少8字）');
  const raw = await readFile(await safeSourcePath(graphRootOf(root), 'factory.graph.json'), 'utf8'), graph = JSON.parse(raw);
  const before = await inspectBindings(root, structuredClone(graph), raw);
  if (typeof expectedGraphHash !== 'string' || expectedGraphHash !== before.graphHash) throw new Error('图或源码已变化，请重新检查后使用最新 graphHash 核验');
  const binding = await bindingFile(root);
  if (binding.error) throw new Error(`先修复绑定文件：${binding.error}`);
  const reviewedAt = new Date().toISOString(), updated = [];
  for (const id of nodeIds) {
    const node = graph.nodes.find(n => n.id === id);
    if (!node || !node.data?.sourceRefs?.length) throw new Error(`组件 ${id} 不存在或缺少源码引用`);
    const refs = [];
    for (const ref of node.data.sourceRefs) {
      const full = await safeSourcePath(root, ref.path), text = await readFile(full, 'utf8'), lines = text.split('\n');
      checkRange(ref, lines);
      const snippet = lines.slice(ref.startLine - 1, ref.endLine).join('\n');
      if (!snippet.trim() || occurrences(lines, snippet.split('\n')).length !== 1) throw new Error(`组件 ${id} 引用片段不唯一，请扩充源码范围以建立可靠锚点`);
      refs.push({ ref: refIdentity(ref), refHash: identityHash(ref), anchorHash: sha(snippet), fileHash: sha(text), snippet });
    }
    binding.value.nodes[id] = { nodeId: id, meaningHash: meaningHash(node), reviewedAt, reviewer, reason: reason.trim(), refs };
    updated.push(id);
  }
  const latestRaw = await readFile(await safeSourcePath(graphRootOf(root), 'factory.graph.json'), 'utf8');
  const latest = await inspectBindings(root, JSON.parse(latestRaw), latestRaw);
  if (latest.graphHash !== expectedGraphHash) throw new Error('核验期间源码变化，未更新绑定');
  binding.value.reviews ??= [];
  binding.value.reviews.push({ reviewedAt, reviewer, reason: reason.trim(), nodeIds: updated, previousBindingHash: sha(binding.raw), reviewedGraphHash: expectedGraphHash });
  await safeSourcePath(graphRootOf(root), 'factory.bindings.json', { allowMissing: true });
  const storage = graphRootOf(root), output = resolve(storage, 'factory.bindings.json'), temp = resolve(storage, `.factory.bindings.${process.pid}.${Date.now()}.tmp`);
  await writeFile(temp, JSON.stringify(binding.value, null, 2) + '\n', { flag: 'wx' });
  await rename(temp, output);
  return { updated, reviewedAt, note: '显式更新的是对应关系基线；并非运行正确性或语义自动认证。', ...(await inspectBindings(root, structuredClone(graph), raw)) };
}
